// Run with the unpacked, integrity-checked npm package directory as argument.
const fs = require('node:fs');
const path = require('node:path');
const packageDir = path.resolve(process.argv[2] || 'tmp/vendor/package');
const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
if (pkg.name !== 'katex' || pkg.version !== '0.16.25') throw new Error('Expected KaTeX 0.16.25');
const output = path.resolve(__dirname, '../extension/vendor');
fs.mkdirSync(output, { recursive: true });
let count = 0;
const css = fs.readFileSync(path.join(packageDir, 'dist/katex.min.css'), 'utf8')
  .replace(/src:[^;}]*?url\(([^)]*\.woff2)\)[^;}]*/g, (_match, filename) => {
    const font = fs.readFileSync(path.join(packageDir, 'dist', filename.replace(/["']/g, '')));
    count++;
    return `src:url(data:font/woff2;base64,${font.toString('base64')}) format("woff2");`;
  });
if (count !== 20 || /url\((?!data:)/.test(css)) throw new Error('Unexpected font references');
fs.writeFileSync(path.join(output, 'katex-assets.js'),
  `/* KaTeX ${pkg.version}, MIT license: LICENSE-katex.txt. Generated by scripts/bundle-katex.cjs. */\n` +
  `globalThis.ChatPDFMathCSS = ${JSON.stringify(css)};\n`);
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(output, 'LICENSE-katex.txt'));
console.log(`Bundled KaTeX CSS and ${count} local WOFF2 fonts; no network requests at export time.`);
